/** FIFA's names that the data sources write otherwise */
const SOURCE_NAME: Record<string, string> = {
  'IR Iran': 'Iran',
  'Korea Republic': 'South Korea',
  'DPR Korea': 'North Korea',
  'Republic of Ireland': 'Ireland',
  'Congo DR': 'DR Congo',
  'China PR': 'China',
  "Côte d'Ivoire": 'Ivory Coast',
  'Cabo Verde': 'Cape Verde Islands',
  'Kyrgyz Republic': 'Kyrgyzstan',
  'The Gambia': 'Gambia',
  Czechia: 'Czech Republic',
  Türkiye: 'Turkey',
  'St. Kitts and Nevis': 'Saint Kitts and Nevis',
  'St. Lucia': 'Saint Lucia',
  'St. Vincent / Grenadines': 'Saint Vincent and the Grenadines',
  'Macau, China': 'Macao',
  Eswatini: 'Swaziland',
  'Timor-Leste': 'East Timor',
}

const key = (name: string) => foldCountry(danishCountry(name))
const BY_NAME = new Map<string, number>()
for (const [rank, name] of RANKING) {
  for (const n of [name, SOURCE_NAME[name]]) if (n) for (const k of [foldCountry(n), key(n)]) if (!BY_NAME.has(k)) BY_NAME.set(k, rank)
}

/** A national team's place on FIFA's list, by any of its names ("Danmark", "Denmark", "Turkey") */
export function fifaRank(names: string[]): number | undefined {
  for (const n of names) {
    const rank = BY_NAME.get(foldCountry(n)) ?? BY_NAME.get(key(n))
    if (rank) return rank
  }
  return undefined
}
